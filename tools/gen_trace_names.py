#!/usr/bin/env python3
"""Generate src/trace_syscalls.h from the x86_64 unistd header."""
import re
import sys

HEADER = "/usr/include/x86_64-linux-gnu/asm/unistd_64.h"
OUT = "src/trace_syscalls.h"

pattern = re.compile(r"^#define\s+__NR_(\w+)\s+(\d+)\s*$")
entries = []
with open(HEADER, "r", encoding="utf-8") as fp:
    for line in fp:
        match = pattern.match(line)
        if match:
            entries.append((int(match.group(2)), match.group(1)))

entries = [
    (number, name) for number, name in entries
    if number <= 110 or number in {
        157, 158, 186, 202, 217, 218, 231, 257, 262, 273,
        288, 293, 318, 334, 435, 437, 439, 471,
    }
]
entries.sort()
with open(OUT, "w", encoding="utf-8") as fp:
    fp.write("/* Generated by tools/gen_trace_names.py; do not edit. */\n")
    fp.write("#ifndef MYSHELL_TRACE_SYSCALLS_H\n")
    fp.write("#define MYSHELL_TRACE_SYSCALLS_H\n\n")
    fp.write("static const char *const trace_syscall_names[512] = {\n")
    for number, name in entries:
        fp.write('    [%d] = "%s",\n' % (number, name))
    fp.write("};\n\n#endif\n")
print("wrote %s (%d syscalls)" % (OUT, len(entries)))
